 # 非眼科词根碰撞
 'Actinic keratosis','Amyotrophic lateral sclerosis','Aortic valve sclerosis','Bladder neck sclerosis',
 'Catheter site macule','Cholangitis sclerosing','Diffuse mesangial sclerosis',
 'Immunoglobulin G4 related sclerosing disease','Keratoacanthoma','Keratosis pilaris',
 'Lichen sclerosus','Lichenoid keratosis','Macule','Mastoptosis','Mitral valve sclerosis',
 'Multiple sclerosis','Multiple sclerosis pseudo relapse','Multiple sclerosis relapse',
