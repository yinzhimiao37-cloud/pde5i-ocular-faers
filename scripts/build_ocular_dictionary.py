def group(pt):
 u=pt.upper()
 if re.search(r'(RETINAL (ARTERY|VEIN|VASCULAR)|OCULAR STROKE|OCULAR ISCHAEMIC|OPHTHALMIC VEIN|OPTIC (ISCHAEMIC|NERVE INFARCTION)|AMAUROSIS FUGAX)',u):
  return 'ocular_vascular_occlusion_ischaemia'
 if re.search(r'(RETIN|MACUL|CHOROID|VITRE|PIGMENT EPITHEL|DRUSEN)',u): return 'retina_choroid_vitreous'
 if re.search(r'(OPTIC|PAPILLOEDEMA)',u): return 'optic_nerve_disc'
 if re.search(r'(GLAUCOMA|OCULAR HYPERTENSION|HYPOTONY OF EYE|INTRAOCULAR PRESSURE)',u): return 'glaucoma_IOP'
 if re.search(r'(CATARACT|\bLENS\b|LENTICULAR|PSEUDOPHAK|APHAK)',u): return 'lens_cataract'
 if re.search(r'(CORNE|CONJUNCTIV|KERAT|UVEIT|IRIS|IRIDO|CYCLITIS|SCLER|ENDOPHTHALMITIS|HYPOPYON|ANTERIOR CHAMBER|PINGUECULA|PTERYGIUM)',u):
  return 'anterior_segment_surface'
 if re.search(r'(EYELID|BLEPHAR|LACRIM|DACRY|HORDEOLUM|CHALAZION|ORBIT|PERIORBIT|MEIBOM|EYELASH|MADAROS|EXOPHTHAL|LAGOPHTHAL|DARK CIRCLES)',u):
  return 'adnexa_lacrimal_orbit'
 if re.search(r'(VISION|VISUAL|BLIND|DIPLOPIA|PHOTOPHOBIA|PHOTOPSIA|CHROMATOPSIA|XANTHOPSIA|CYANOPSIA|DYSCHROMATOPSIA|AMAUROSIS|SCOTOMA|METAMORPHOPSIA|PALINOPSIA|HALO|KALEIDOSCOPE|ASTHENOPIA|HEMIANOPIA)',u):
  return 'visual_symptoms_function'
 return 'other_ocular'

def main():
 d=pd.read_csv(SOURCE)
 extra={x.upper() for x in EXTRA}; excluded={x.upper() for x in EXCLUDE_EXACT}
 d['pt']=d.pt.str.upper()
 d['semantic_candidate']=d.keyword_candidate | d.pt.isin(extra)
 d['include_ocular']=d.semantic_candidate & ~d.pt.isin(excluded)
 d['ocular_group']=d.pt.map(group).where(d.include_ocular,'EXCLUDED')
 d['review_reason']='Not generated by ocular keyword screen'
 d.loc[d.keyword_candidate,'review_reason']='Included after semantic review of keyword candidate'
 d.loc[d.pt.isin(extra),'review_reason']='Added by prespecified ophthalmic synonym review'
 d.loc[d.pt.isin(excluded),'review_reason']='Excluded: non-ocular collision or procedure/test/exposure concept'
 # 每个候选必须得到明确结论；没有按计数、ROR或P值选择。
 assert not d.loc[d.semantic_candidate,'include_ocular'].isna().any()
 final=d.loc[d.semantic_candidate,['pt','include_ocular','ocular_group','review_reason']].sort_values(['include_ocular','ocular_group','pt'],ascending=[False,True,True])
 final.to_csv(R/'ocular_PT_dictionary.csv',index=False)
 inc=final[final.include_ocular]
 meta={'status':'frozen','scope':'project-specific ocular clinical PT dictionary; not official MedDRA SOC',
       'review_basis':'PT semantics only; counts and disproportionality not read by this script',
       'included_PT':len(inc),'excluded_candidates':int((~final.include_ocular).sum()),
       'groups':inc.ocular_group.value_counts().to_dict(),
       'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest()}
 (R/'ocular_dictionary_audit.json').write_text(json.dumps(meta,indent=2),encoding='utf-8')
 print(json.dumps(meta,indent=2))

if __name__=='__main__':main()
